            (function(){
                const track = document.getElementById('galleryTrack');
                const prev = document.getElementById('galPrev');
                const next = document.getElementById('galNext');
                const slider = document.getElementById('gallerySlider');
                const gap = 12; // must match CSS gap
                function itemWidth(){
                    const item = track.querySelector('.gallery-item');
                    return item ? item.getBoundingClientRect().width : 160;
                }
                function visibleCount(){
                    const sw = slider.getBoundingClientRect().width;
                    const w = itemWidth();
                    return Math.max(1, Math.floor((sw + gap) / (w + gap)));
                }
                let index = 0;
                function clampIndex(){
                    const total = track.children.length;
                    const maxIndex = Math.max(0, total - visibleCount());
                    if(index < 0) index = 0; if(index > maxIndex) index = maxIndex;
                    prev.disabled = index === 0; next.disabled = index === maxIndex;
                }
                function update(){
                    const w = itemWidth();
                    const x = -(index * (w + gap));
                    track.style.transform = `translateX(${x}px)`;
                    clampIndex();
                }
                prev.addEventListener('click', ()=>{ index--; update(); });
                next.addEventListener('click', ()=>{ index++; update(); });
                window.addEventListener('resize', ()=>{ clampIndex(); update(); });
                // init
                update();
            })();
